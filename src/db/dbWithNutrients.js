const vitaminUnits = {
  vitaminA: { label: "Vitamina A (RAE)", unit: "µg" },
  vitaminB1: { label: "Vitamina B1", unit: "mg" },
  vitaminB2: { label: "Vitamina B2", unit: "mg" },
  vitaminB3: { label: "Vitamina B3", unit: "mg" },
  vitaminB6: { label: "Vitamina B6", unit: "mg" },
  vitaminC: { label: "Vitamina C", unit: "mg" },
  vitaminD: { label: "Vitamina D", unit: "µg" },
  vitaminE: { label: "Vitamina E", unit: "mg" },
  vitaminB12: { label: "Vitamina B12", unit: "µg" },
  folate: { label: "Folato", unit: "µg" },
};

const makeVitaminProfile = (
  sourceFood,
  record,
  values = {},
  note = "",
) => {
  // Values are per 100 g; null means not quantified, not zero.
  const per100g = Object.fromEntries(
    Object.keys(vitaminUnits).map((nutrient) => [
      nutrient,
      values[nutrient] ?? null,
    ]),
  );

  return {
    basisGrams: 100,
    source: "TBCA",
    sourceFood,
    sourceUrl: record ? tbcaRecordUrl(record) : tbcaCatalogUrl,
    per100g,
    highlights: Object.entries(per100g)
      .filter(([, amount]) => amount !== null && amount > 0)
      .map(([nutrient, amount]) => ({
        nutrient,
        label: vitaminUnits[nutrient].label,
        amount,
        unit: vitaminUnits[nutrient].unit,
      })),
    ...(note ? { note } : {}),
  };
};

